export var Dh = RegExp(
    `(?<![A-Za-z-])(` +
      [...Eh.keys()]
        .sort((e, t) => t.length - e.length)
        .map((e) => e.replace(/[.*+?^${}()|[\]\\]/g, `\\$&`))
        .join(`|`) +
      `)(?![A-Za-z])`,
    `gi`,
  );

export var Oh = `(Mon|Tues|Wednes|Thurs|Fri|Satur|Sun)day`;

export var kh = `(January|February|March|April|May|June|July|August|September|October|November|December)`;

export var Ah = RegExp(`\\b(${Oh}|${kh}) through (${Oh}|${kh})\\b`, `g`);

export function jh(e, t) {
  let n = e[0] ?? ``;
  return n !== n.toUpperCase() ||
    n === n.toLowerCase() ||
    (e.length > 1 &&
      e[1] === e[1]?.toUpperCase() &&
      e[1] !== e[1]?.toLowerCase())
    ? t
    : t[0].toUpperCase() + t.slice(1);
}

export function Mh(e, t) {
  return t !== `uk` || !e
    ? e
    : e
        .replace(Dh, (e) => {
          let t = Eh.get(e.toLowerCase());
          return t === void 0 || t === e.toLowerCase() ? e : jh(e, t);
        })
        .replace(Ah, `$1 to $4`);
}

export function Nh(e, t) {
  return t === `uk` ? { ...e, en: Mh(e.en, t) } : e;
}

export function Ph(e, t) {
  return t === `uk` ? e.map((e) => Nh(e, t)) : e;
}